// Copy text to the clipboard from a plain-HTTP page. navigator.clipboard is
// only defined in secure contexts (HTTPS / localhost), and fjord is normally
// reached over http://host:3567 -- so fall back to the legacy execCommand path
// through an off-screen textarea, which still works everywhere.
export async function copyText(text: string): Promise<boolean> {
  try {
    if (navigator.clipboard && window.isSecureContext) {
      await navigator.clipboard.writeText(text);
      return true;
    }
  } catch {}
  try {
    const ta = document.createElement('textarea');
    ta.value = text;
    ta.setAttribute('readonly', '');
    ta.style.position = 'fixed';
    ta.style.top = '-1000px';
    document.body.appendChild(ta);
    ta.select();
    ta.setSelectionRange(0, text.length);
    const ok = document.execCommand('copy');
    document.body.removeChild(ta);
    return ok;
  } catch {
    return false;
  }
}
